// Regenerate Orbit's SVGs and every Mac app icon size, without network access.
// Run from web/: npm run brand
import { readFileSync, writeFileSync } from "node:fs";
import { initWasm, Resvg } from "@resvg/resvg-wasm";
import { orbitMarkArtwork } from "../src/lib/orbit";

const artwork = orbitMarkArtwork();
const mark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" fill="none">\n  <!-- Orbit. Generated by web/scripts/brand.ts. -->\n${artwork}\n</svg>\n`;
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" fill="none">\n  <!-- Orbit, with the Mac app icon's transparent margin. -->\n  <g transform="translate(100 100) scale(${824 / 48})">\n${artwork}\n  </g>\n</svg>\n`;
writeFileSync("../brand/mark.svg", mark);
writeFileSync("public/favicon.svg", mark);
writeFileSync("../brand/app-icon.svg", icon);

await initWasm(readFileSync("node_modules/@resvg/resvg-wasm/index_bg.wasm"));
const catalog = "../mac/App/Resources/Assets.xcassets/AppIcon.appiconset";
const { images } = JSON.parse(readFileSync(`${catalog}/Contents.json`, "utf8")) as {
  images: { filename: string; size: string; scale: string }[];
};
for (const image of images) {
  const pixels = parseInt(image.size, 10) * parseInt(image.scale, 10);
  const png = new Resvg(icon, { fitTo: { mode: "width", value: pixels } }).render().asPng();
  writeFileSync(`${catalog}/${image.filename}`, png);
}
console.log(`Orbit: mark, favicon, app-icon SVG and ${images.length} Mac icon sizes`);
